func TestDurablePublicationEpochFencesABAEvenWithoutIntermediateAggregate(t *testing.T) {
	stubReceiptCompile(t)
	api := newFakeAPI()
	cr := testCR("alpha", nil)
	api.addCR(cr)
	apiServer := httptest.NewTLSServer(api.handler(t))
	defer apiServer.Close()
	apiClient := kube.New(&kube.Config{BaseURL: apiServer.URL, TLS: receipttest.Trust(apiServer)})
	opts := Options{Namespace: "warmor-system", ConfigMapNamespace: "warmor-system", ConfigMapName: "warmor-effective-policy"}
	ctl := New(apiClient, opts)
	k := receipttest.NewKube(t)
	posture := nodereceipt.Posture{Audit: true}
	if err := ctl.EnableReceipts(receipttest.Config(k, nil), posture); err != nil {
		t.Fatal(err)
	}
	server := httptest.NewTLSServer(ctl.ReceiptHandler())
	defer server.Close()
	ctx := context.Background()
	if _, err := ctl.Reconcile(ctx); err != nil {
		t.Fatal(err)
	}
	a, err := ctl.publishedManifest(ctx)
	if err != nil {
		t.Fatal(err)
	}
	cmA, err := ctl.readConfigMap(ctx)
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	path, token := filepath.Join(dir, "manifest"), filepath.Join(dir, "token")
	writeManifest := func(m nodereceipt.Manifest) {
		t.Helper()
		b, _ := json.Marshal(m)
		if err := os.WriteFile(path, b, 0600); err != nil {
			t.Fatal(err)
		}
	}
	writeManifest(a)
	if err := os.WriteFile(token, []byte("bound-token-a"), 0600); err != nil {
		t.Fatal(err)
	}
	active := nodereceipt.Activation{Digest: a.Digest, ABI: a.ABI, ArtifactCompiler: a.ArtifactCompiler, DefaultAction: a.DefaultAction, Posture: a.Posture, ActivatedAt: time.Now().Add(-time.Second)}
	c, err := nodereceipt.NewClient(nodereceipt.ClientConfig{URL: server.URL, TLS: receipttest.Trust(server), TokenPath: token, ManifestPath: path, Active: func() (nodereceipt.Activation, error) { return active, nil }})
	if err != nil {
		t.Fatal(err)
	}
	if err := c.Report(ctx); err != nil {
		t.Fatal(err)
	}
	assertAll := func(want bool) {
		t.Helper()
		m, err := ctl.publishedManifest(ctx)
		if err != nil {
			t.Fatal(err)
		}
		r, err := ctl.receipts.Aggregate(ctx, m)
		if err != nil || r.All != want {
			t.Fatalf("aggregate %+v %v, want %t", r, err, want)
		}
	}
	assertAll(true)
	// The epoch is durable and stable for no-op publication/reconcile and a
	// new controller process, not a random value regenerated by every read.
	if _, err := ctl.Reconcile(ctx); err != nil {
		t.Fatal(err)
	}
	stable, err := ctl.publishedManifest(ctx)
	if err != nil || stable.ID() != a.ID() {
		t.Fatal("unchanged publication changed epoch", err)
	}
	restarted := New(apiClient, opts)
	if err := restarted.EnableReceipts(receipttest.Config(k, nil), posture); err != nil {
		t.Fatal(err)
	}
	if _, err := restarted.Reconcile(ctx); err != nil {
		t.Fatal(err)
	}
	stable, err = restarted.publishedManifest(ctx)
	if err != nil || stable.ID() != a.ID() {
		t.Fatal("restart lost durable epoch", err)
	}
	assertAll(true) // the original server's receipt is still current A
	// Missing/old/contradictory build claims must fail before publication;
	// treating them as another receipt identity would contradict compiler-7.
	for _, claims := range []*policybuild.Metadata{
		nil,
		{Compiler: "warmor-yaml/6", DefaultAction: a.DefaultAction},
		{Compiler: compiler.Identity, DefaultAction: "deny"},
	} {
		module := wasmtest.VersionedConstPolicy(1, a.ABI)
		if claims != nil {
			var err error
			module, err = policybuild.Append(module, *claims)
			if err != nil {
				t.Fatal(err)
			}
		}
		if synced, err := ctl.syncConfigMap(ctx, cmA, module, "effective:bad-build", []string{"warmor-system/alpha"}, cmA.Data[SnapshotDataKey]); err == nil || synced {
			t.Fatal("unsupported metadata published")
		}
		assertAll(true)
		stable, err := ctl.publishedManifest(ctx)
		if err != nil || stable.ID() != a.ID() {
			t.Fatal("rejected build changed committed epoch", err)
		}
	}
	// Failed publication attempts (including optimistic conflicts) cannot
	// commit an epoch or revoke A as if a transition had succeeded.
	bModule, err := policybuild.Append(wasmtest.VersionedConstPolicy(1, a.ABI), policybuild.Metadata{Compiler: compiler.Identity, DefaultAction: a.DefaultAction})
	if err != nil {
		t.Fatal(err)
	}
	for _, code := range []int{http.StatusConflict, http.StatusServiceUnavailable} {
		api.mu.Lock()
		api.configMapWriteError = code
		api.mu.Unlock()
		if synced, err := ctl.syncConfigMap(ctx, cmA, bModule, "effective:b", []string{"warmor-system/alpha"}, cmA.Data[SnapshotDataKey]); err == nil || synced {
			t.Fatal("failed publication acknowledged")
		}
		api.mu.Lock()
		api.configMapWriteError = 0
		api.mu.Unlock()
		stable, err := ctl.publishedManifest(ctx)
		if err != nil || stable.ID() != a.ID() {
			t.Fatal("failed write changed durable epoch", err)
		}
		assertAll(true)
	}
	// Call publication directly so neither server.Aggregate nor Reconcile sees
	// B. This models two successful transitions between aggregation ticks.
	if synced, err := ctl.syncConfigMap(ctx, cmA, bModule, "effective:b", []string{"warmor-system/alpha"}, cmA.Data[SnapshotDataKey]); err != nil || !synced {
		t.Fatalf("publish B: %t %v", synced, err)
	}
	cmB, err := ctl.readConfigMap(ctx)
	if err != nil {
		t.Fatal(err)
	}
	var b nodereceipt.Manifest
	if err := json.Unmarshal([]byte(cmB.Data[nodereceipt.ManifestDataKey]), &b); err != nil {
		t.Fatal(err)
	}
	if b.PublicationEpoch == a.PublicationEpoch {
		t.Fatal("B reused A epoch")
	}
	if synced, err := ctl.syncConfigMap(ctx, cmB, cmA.BinaryData[PolicyDataKey], a.Revision, []string{"warmor-system/alpha"}, cmA.Data[SnapshotDataKey]); err != nil || !synced {
		t.Fatalf("publish A again: %t %v", synced, err)
	}
	aAgain, err := ctl.publishedManifest(ctx)
	if err != nil {
		t.Fatal(err)
	}
	if aAgain.PublicationEpoch == a.PublicationEpoch || aAgain.PublicationEpoch == b.PublicationEpoch {
		t.Fatal("ABA reused a publication epoch")
	}
	contentA, contentAgain := a, aAgain
	contentA.PublicationEpoch, contentAgain.PublicationEpoch = "", ""
	if contentA.ID() != contentAgain.ID() {
		t.Fatal("fixture is not identical-content ABA")
	}
	assertAll(false)
	if _, err := ctl.Reconcile(ctx); err != nil {
		t.Fatal(err)
	}
	if cr.Status.Phase == PhaseActive || cr.Status.NodesApplied != 0 || cr.Status.LastApplied != "" {
		t.Fatalf("ABA resurrected applied status: %+v", cr.Status)
	}
	writeManifest(aAgain)
	_ = c.Report(ctx) // obsolete session is withdrawn and forgotten
	if err := c.Report(ctx); err != nil {
		t.Fatal(err)
	}
	assertAll(true) // genuine fresh report for the new epoch is eligible
	if _, err := ctl.Reconcile(ctx); err != nil {
		t.Fatal(err)
	}
	if cr.Status.Phase != PhaseActive {
		t.Fatalf("fresh report not reflected: %+v", cr.Status)
	}
	// Upgrade from the old deterministic manifest must publish a fresh epoch,
	// not leave legacy evidence eligible or keep churning epochs thereafter.
	api.mu.Lock()
	legacy := aAgain
	legacy.PublicationEpoch = ""
	legacyBytes, marshalErr := json.Marshal(legacy)
	if marshalErr != nil {
		api.mu.Unlock()
		t.Fatal(marshalErr)
	}
	api.configMaps["warmor-system/warmor-effective-policy"].Data[nodereceipt.ManifestDataKey] = string(legacyBytes)
	api.mu.Unlock()
	if _, err := ctl.publishedManifest(ctx); err == nil {
		t.Fatal("legacy manifest without publication epoch eligible")
	}
	if _, err := ctl.Reconcile(ctx); err != nil {
		t.Fatal(err)
	}
	migrated, err := ctl.publishedManifest(ctx)
	if err != nil || migrated.PublicationEpoch == "" || migrated.ID() == aAgain.ID() {
		t.Fatal("legacy publication not fenced", err)
	}
	assertAll(false)
	if _, err := ctl.Reconcile(ctx); err != nil {
		t.Fatal(err)
	}
	stable, err = ctl.publishedManifest(ctx)
	if err != nil || stable.ID() != migrated.ID() {
		t.Fatal("legacy migration epoch unstable", err)
	}
}
