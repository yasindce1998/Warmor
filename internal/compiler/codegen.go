func writeRuleCheckBinary(b *strings.Builder, rule Rule, eventType string, ruleIndex int) {
	action := actionConstant(rule.Action)
	if rule.Mode == "audit" && rule.Action == "deny" {
		action = "ACTION_AUDIT_DENY"
	}

	// Only an enforcing deny may act on a possible (unknown-input) match.
	// An uncertain audit/log rule must not return before a later definite
	// deny or default deny. Nonblocking rules require a definite match.
	condExpr := generateConditionExprBounds(rule.Conditions, eventType, rule.Action == "deny" && rule.Mode != "audit")
	if condExpr == "" {
		condExpr = "true"
	}
	if window := temporalWindowExpr(rule.Temporal); window != "" {
		// The action applies only outside the permitted window.
		condExpr = fmt.Sprintf("(%s) && !(%s)", condExpr, window)
	}

	b.WriteString(fmt.Sprintf("    // Rule: %s\n", strconv.QuoteToASCII(rule.Name)))
	b.WriteString(fmt.Sprintf("    if %s {\n", condExpr))
	b.WriteString(fmt.Sprintf("        LAST_MATCHED = %d;\n", ruleIndex))
	b.WriteString(fmt.Sprintf("        return %s;\n", action))
	b.WriteString("    }\n\n")
}

