func writeMallocFree(b *strings.Builder) {
	b.WriteString(`#[no_mangle]
pub extern "C" fn malloc(size: usize) -> *mut u8 {
    if size == 0 { return core::ptr::null_mut(); }
    match Layout::from_size_align(size, 1) {
        Ok(layout) => unsafe { ALLOCATOR.alloc(layout) },
        Err(_) => core::ptr::null_mut(),
    }
}

#[no_mangle]
pub extern "C" fn free(ptr: *mut u8, size: usize) {
    if ptr.is_null() || size == 0 { return; }
    if let Ok(layout) = Layout::from_size_align(size, 1) {
        unsafe { ALLOCATOR.dealloc(ptr, layout) }
    }
}

// Bounded LIFO allocator for no_std. The host keeps the event buffer alive
// and frees each temporary declaration/reason buffer before allocating again.
// Store the previous position so freeing the top also reclaims alignment.
use core::alloc::{GlobalAlloc, Layout};

struct BumpAllocator;

unsafe impl GlobalAlloc for BumpAllocator {
    unsafe fn alloc(&self, layout: Layout) -> *mut u8 {
        let base = core::ptr::addr_of_mut!(HEAP) as *mut u8;
        let mask = layout.align() - 1;
        let address = match (base as usize).checked_add(HEAP_POS)
            .and_then(|v| v.checked_add(core::mem::size_of::<usize>()))
            .and_then(|v| v.checked_add(mask)) {
            Some(v) => v & !mask,
            None => return core::ptr::null_mut(),
        };
        let aligned = address - base as usize;
        let new_pos = match aligned.checked_add(layout.size()) {
            Some(v) if v <= 65536 => v,
            _ => return core::ptr::null_mut(),
        };
        core::ptr::write_unaligned((address - core::mem::size_of::<usize>()) as *mut usize, HEAP_POS);
        HEAP_POS = new_pos;
        address as *mut u8
    }

    unsafe fn dealloc(&self, ptr: *mut u8, layout: Layout) {
        let base = core::ptr::addr_of_mut!(HEAP) as usize;
        let address = ptr as usize;
        if address < base + core::mem::size_of::<usize>() || address > base + 65536 { return; }
        let offset = address - base;
        if offset.checked_add(layout.size()) != Some(HEAP_POS) { return; }
        let previous = core::ptr::read_unaligned((address - core::mem::size_of::<usize>()) as *const usize);
        if previous <= offset - core::mem::size_of::<usize>() { HEAP_POS = previous; }
    }
}

#[global_allocator]
static ALLOCATOR: BumpAllocator = BumpAllocator;

static mut HEAP: [u8; 65536] = [0u8; 65536];
static mut HEAP_POS: usize = 0;

#[panic_handler]
fn panic(_info: &core::panic::PanicInfo) -> ! {
    core::arch::wasm32::unreachable()
}

`)
}

func writeReasonTable(b *strings.Builder, policy *Policy) {
	b.WriteString("static RULE_REASONS: &[&str] = &[\n")
	for _, rule := range policy.Rules {
		reason := rule.Reason
		if reason == "" {
			reason = fmt.Sprintf("Rule: %s", rule.Name)
		}
		b.WriteString(fmt.Sprintf("    %s,\n", rustString(reason)))
	}
	b.WriteString("];\n\n")
	b.WriteString("static mut LAST_MATCHED: u32 = 0xFFFFFFFF;\n\n")
}

func writeEvaluateEventFunction(b *strings.Builder, policy *Policy) {
	b.WriteString(`#[no_mangle]
pub extern "C" fn evaluate_event(offset: u32) -> i32 {
    unsafe {
        let base = offset as *const u8;
        let event_type = *base.add(OFF_EVENT_TYPE);
        LAST_MATCHED = 0xFFFFFFFF;
        match event_type {
            EVENT_PROCESS => evaluate_process(base),
            EVENT_FILE => evaluate_file(base),
            EVENT_NETWORK => evaluate_network(base),
            _ => ACTION_DENY,
        }
    }
}

`)

	writeProcessEvaluatorBinary(b, policy)
	writeFileEvaluatorBinary(b, policy)
	writeNetworkEvaluatorBinary(b, policy)
}

func writeProcessEvaluatorBinary(b *strings.Builder, policy *Policy) {
	rules := rulesForEvent(policy, "process")
	defaultAction := actionConstant(policy.DefaultAction)

	b.WriteString("unsafe fn evaluate_process(base: *const u8) -> i32 {\n")
	b.WriteString("    let pid = read_u32(base, OFF_PID);\n")
	b.WriteString("    let uid = read_u32(base, OFF_UID);\n")
	b.WriteString("    let gid = read_u32(base, OFF_GID);\n")
	b.WriteString("    let comm = read_str(base, OFF_COMM, OFF_COMM_LEN);\n")
	b.WriteString("    let path = read_str(base, OFF_PRIMARY_STR, OFF_PRIMARY_STR_LEN);\n")
	if FieldsRead(policy)[0]&FieldBitArgs != 0 {
		// Unknown input is handled by each rule, preserving first-match
		// order and per-rule audit/log actions instead of a blanket DENY.
		b.WriteString(`    let args_len = get_field_str(15, core::ptr::null_mut(), 0) as usize;
    let mut args_buf = [0u8; 16384];
    let (args_known, args) = if args_len <= args_buf.len()
        && get_field_str(15, args_buf.as_mut_ptr(), args_len as u32) as usize == args_len {
        match core::str::from_utf8(&args_buf[..args_len]) {
            Ok(s) => (true, s),
            Err(_) => (false, ""),
        }
    } else {
        (false, "")
    };
`)
	}
	writeTemporalReads(b)
	b.WriteString("    let _ = (pid, gid, comm, wall, age_ms);\n")

	for _, rule := range rules {
		writeRuleCheckBinary(b, rule, "process", globalRuleIndex(policy, rule))
	}
	b.WriteString(fmt.Sprintf("    %s\n", defaultAction))
	b.WriteString("}\n\n")
}

