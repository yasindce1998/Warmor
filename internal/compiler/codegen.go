// For unavailable callback fields, nonblocking rules require a definite
// match while enforcing deny uses a possible match. Negation flips the
// bounds. This never escalates a rule's action and preserves rule order.
func generateConditionExprBounds(conds Conditions, eventType string, possible bool) string {
	var parts []string
	conditionExpr := func(c Condition, upper bool) string {
		expr := conditionToRustBinary(c, eventType)
		known := ""
		if eventType == "process" && c.Field == "args" {
			known = "args_known"
		}
		if eventType == "network" && c.Field == "operation" {
			known = "operation_known"
		}
		if known != "" {
			if upper {
				return fmt.Sprintf("(!%s || (%s))", known, expr)
			}
			return fmt.Sprintf("(%s && (%s))", known, expr)
		}
		return expr
	}

	if len(conds.All) > 0 {
		allParts := make([]string, 0, len(conds.All))
		for _, c := range conds.All {
			expr := conditionExpr(c, possible)
			if expr != "" {
				allParts = append(allParts, expr)
			}
		}
		if len(allParts) > 0 {
			parts = append(parts, strings.Join(allParts, " && "))
		}
	}

	if len(conds.Any) > 0 {
		anyParts := make([]string, 0, len(conds.Any))
		for _, c := range conds.Any {
			expr := conditionExpr(c, possible)
			if expr != "" {
				anyParts = append(anyParts, expr)
			}
		}
		if len(anyParts) > 0 {
			parts = append(parts, fmt.Sprintf("(%s)", strings.Join(anyParts, " || ")))
		}
	}

	if len(conds.Not) > 0 {
		for _, c := range conds.Not {
			expr := conditionExpr(c, !possible)
			if expr != "" {
				parts = append(parts, fmt.Sprintf("!(%s)", expr))
			}
		}
	}

	return strings.Join(parts, " && ")
}

func conditionToRustBinary(c Condition, eventType string) string {
	fieldExpr := fieldToRustBinary(c.Field, eventType)

	switch c.Operator {
	case "eq":
		return formatEqBinary(fieldExpr, c.Field, c.Value)
	case "not":
		return formatNotBinary(fieldExpr, c.Field, c.Value)
	case "glob":
		pattern, _ := c.Value.(string)
		return fmt.Sprintf("matches_glob(%s, %s)", fieldExpr, rustString(pattern))
	case "any_of":
		return formatAnyOfBinary(fieldExpr, c.Field, c.Value)
	case "none_of":
		return formatNoneOfBinary(fieldExpr, c.Field, c.Value)
	case "gt":
		return fmt.Sprintf("%s > %s", fieldExpr, formatNumeric(c.Value))
	case "lt":
		return fmt.Sprintf("%s < %s", fieldExpr, formatNumeric(c.Value))
	case "gte":
		return fmt.Sprintf("%s >= %s", fieldExpr, formatNumeric(c.Value))
	case "lte":
		return fmt.Sprintf("%s <= %s", fieldExpr, formatNumeric(c.Value))
	case "starts_with":
		s, _ := c.Value.(string)
		return fmt.Sprintf("str_starts_with(%s, %s)", fieldExpr, rustString(s))
	case "contains":
		s, _ := c.Value.(string)
		return fmt.Sprintf("str_contains(%s, %s)", fieldExpr, rustString(s))
	default:
		return "true"
	}
}

func fieldToRustBinary(field string, eventType string) string {
	switch field {
	case "pid":
		return "pid"
	case "uid":
		return "uid"
	case "gid":
		return "gid"
	case "comm":
		return "comm"
	case "path":
		if eventType == "process" {
			return "path"
		}
		return "path"
	case "args":
		return "args"
	case "operation":
		return "operation"
	case "protocol":
		return "protocol"
	case "remote_addr":
		return "remote_addr"
	case "flags":
		return "flags"
	case "remote_port":
		return "remote_port"
	case "local_port":
		return "local_port"
	default:
		return field
	}
}

func formatEqBinary(fieldExpr, field string, value interface{}) string {
	if isNumericField(field) {
		return fmt.Sprintf("%s == %s", fieldExpr, formatNumeric(value))
	}
	s := fmt.Sprintf("%v", value)
	return fmt.Sprintf("%s == %s", fieldExpr, rustString(s))
}

func formatNotBinary(fieldExpr, field string, value interface{}) string {
	if isNumericField(field) {
		return fmt.Sprintf("%s != %s", fieldExpr, formatNumeric(value))
	}
	s := fmt.Sprintf("%v", value)
	return fmt.Sprintf("%s != %s", fieldExpr, rustString(s))
}

func formatAnyOfBinary(fieldExpr, field string, value interface{}) string {
	items := toSlice(value)
	if isNumericField(field) {
		rustType := fieldRustType(field)
		vals := make([]string, 0, len(items))
		for _, item := range items {
			vals = append(vals, formatNumeric(item))
		}
		return fmt.Sprintf("any_of_%s(%s, &[%s])", rustType, fieldExpr, strings.Join(vals, ", "))
	}
	vals := make([]string, 0, len(items))
	for _, item := range items {
		// GenerateRust validates operand types before reaching codegen.
		s, _ := item.(string)
		vals = append(vals, rustString(s))
	}
	return fmt.Sprintf("any_of_str(%s, &[%s])", fieldExpr, strings.Join(vals, ", "))
}

func formatNoneOfBinary(fieldExpr, field string, value interface{}) string {
	items := toSlice(value)
	if isNumericField(field) {
		rustType := fieldRustType(field)
		vals := make([]string, 0, len(items))
		for _, item := range items {
			vals = append(vals, formatNumeric(item))
		}
		return fmt.Sprintf("none_of_%s(%s, &[%s])", rustType, fieldExpr, strings.Join(vals, ", "))
	}
	vals := make([]string, 0, len(items))
	for _, item := range items {
		// GenerateRust validates operand types before reaching codegen.
		s, _ := item.(string)
		vals = append(vals, rustString(s))
	}
	return fmt.Sprintf("none_of_str(%s, &[%s])", fieldExpr, strings.Join(vals, ", "))
}

func globalRuleIndex(policy *Policy, rule Rule) int {
	for i, r := range policy.Rules {
		if r.Name == rule.Name {
			return i
		}
	}
	return 0
}

func isNumericField(field string) bool {
	switch field {
	case "pid", "uid", "gid", "flags", "remote_port", "local_port":
		return true
	default:
		return false
	}
}

func fieldRustType(field string) string {
	switch field {
	case "pid", "uid", "gid", "flags":
		return "u32"
	case "remote_port", "local_port":
		return "u16"
	default:
		return "str"
	}
}

func formatNumeric(value interface{}) string {
	// GenerateRust validates concrete numeric types and unsigned bounds first.
	// Never interpolate arbitrary Stringer output into Rust source.
	switch v := value.(type) {
	case int:
		return fmt.Sprintf("%d", v)
	case int64:
		return fmt.Sprintf("%d", v)
	case uint64:
		return strconv.FormatUint(v, 10)
	case float64:
		return strconv.FormatUint(uint64(v), 10)
	default:
		panic("unvalidated numeric condition")
	}
}

// rustString emits a Rust UTF-8 string literal, not Go's incompatible %q.
func rustString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"', '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		default:
			// Escape format/bidi controls too: Rust rejects some raw direction
			// controls in source literals even though they are valid UTF-8.
			if !unicode.IsPrint(r) {
				fmt.Fprintf(&b, "\\u{%x}", r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

// crateIdentifier never embeds untrusted text into TOML or artifact paths.
// Preserve legacy names where safe; other display names get a stable ID.
func crateIdentifier(name string) string {
	if len(name) > 0 && len(name) <= 64 {
		safe := true
		for _, r := range name {
			if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '-' || r == '_' || r == ' ') {
				safe = false
			}
		}
		if safe {
			return strings.NewReplacer("-", "_", " ", "_").Replace(name)
		}
	}
	return fmt.Sprintf("id_%x", sha256.Sum256([]byte(name)))
}

func toSlice(value interface{}) []interface{} {
	switch v := value.(type) {
	case []interface{}:
		return v
	case []string:
		result := make([]interface{}, len(v))
		for i, s := range v {
			result[i] = s
		}
		return result
	default:
		return []interface{}{value}
	}
}

func rulesForEvent(policy *Policy, eventType string) []Rule {
	var rules []Rule
	for _, r := range policy.Rules {
		if r.Event == eventType {
			rules = append(rules, r)
		}
	}
	return rules
}

func actionConstant(action string) string {
	switch action {
	case "allow":
		return "ACTION_ALLOW"
	case "deny":
		return "ACTION_DENY"
	case "log":
		return "ACTION_LOG"
	default:
		return "ACTION_ALLOW"
	}
}

